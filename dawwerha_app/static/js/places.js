// Distance between two points in km
function distanceKm(lat1, lng1, lat2, lng2) {
    const dLat = (lat2 - lat1) * 111;
    const dLng = (lng2 - lng1) * 111 * Math.cos(lat1 * Math.PI / 180);
    return Math.sqrt(dLat * dLat + dLng * dLng);
}

// The closest place to a point, written like "Al-Tireh, Ramallah"
function nearestPlace(lat, lng) {
    let best = PLACES[0];
    let bestDistance = distanceKm(lat, lng, best[2], best[3]);

    PLACES.forEach(function (place) {
        const d = distanceKm(lat, lng, place[2], place[3]);
        if (d < bestDistance) {
            best = place;
            bestDistance = d;
        }
    });

    let name = best[0];
    if (best[0] !== best[1]) {
        name = best[0] + ', ' + best[1];
    }

    // Far from every place on the list
    if (bestDistance > 3) {
        name = 'Near ' + name;
    }
    return name;
}